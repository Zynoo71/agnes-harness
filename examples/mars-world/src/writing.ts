/** A character takes this many grid units across, its gap included. */
export const ADVANCE = 3

/** The characters it can write, for a tool's description. */
export const WRITABLE = 'A–Z, 0–9, space and ! ? - ♥'

/**
 * The strokes for `text`, laid out on the ground: centred on (cx, cz), `scale` metres a grid unit,
 * reading west to east with the tops of the letters to the north (world z grows south). Returns the
 * strokes in writing order and the text's width and height in metres.
 */
export function layout(text: string, cx: number, cz: number, scale: number) {
  const chars = [...text]
  const width = (chars.length * ADVANCE - 1) * scale
  const height = 4 * scale
  const x0 = cx - width / 2
  const strokes: { x: number; z: number }[][] = []
  chars.forEach((c, i) => {
    for (const line of GLYPHS[c] ?? [])
      strokes.push(
        line.map(([x, y]) => ({ x: x0 + (i * ADVANCE + x) * scale, z: cz + height / 2 - y * scale })),
      )
  })
  return { strokes, width, height }
}
